"""Nonzero prevhash, merkle and BIP310 vectors for the live PoW gate."""
import hashlib
import unittest
from decimal import Decimal
from fractions import Fraction

from pow_validator import (DIFF_ONE_TARGET, MAX_TARGET, build_stratum_header,
                           hash_header, target_from_difficulty,
                           validate_stratum_share)


def sha256d(data):
    return hashlib.sha256(hashlib.sha256(data).digest()).digest()


def job():
    return ["job", bytes(range(32)).hex(), "010203", "040506", [],
            "20000002", "1d00ffff", "65000000", True]


class StratumProofTests(unittest.TestCase):
    def test_header_endianness_and_coinbase_merkle_branches(self):
        params = job()
        params[4] = ["11" * 32, "22" * 32]
        header = build_stratum_header(params, "aabb", "ccdd", "65000001", "12345678")
        root = sha256d(bytes.fromhex("010203aabbccdd040506"))
        root = sha256d(root + bytes.fromhex("11" * 32))
        root = sha256d(root + bytes.fromhex("22" * 32))
        expected = (bytes.fromhex("02000020" +
                    "03020100070605040b0a09080f0e0d0c13121110171615141b1a19181f1e1d1c") +
                    root + bytes.fromhex("01000065ffff001d78563412"))
        self.assertEqual(header, expected)
        self.assertEqual(len(header), 80)

    def test_reconstruct_bitcoin_genesis_block(self):
        # Public Bitcoin genesis coinbase data; root is independently fixed by
        # the published genesis header, not generated by this implementation.
        coinbase = (
            "0100000001" + "00" * 32 + "ffffffff4d"
            "04ffff001d0104455468652054696d65732030332f4a616e2f32303039204368616e"
            "63656c6c6f72206f6e206272696e6b206f66207365636f6e64206261696c6f757420"
            "666f722062616e6b73ffffffff0100f2052a01000000434104678afdb0fe55482719"
            "67f1a67130b7105cd6a828e03909a67962e0ea1f61deb649f6bc3f4cef38c4f3550"
            "4e51ec112de5c384df7ba0b8d578a4c702b6bf11d5fac00000000")
        params = ["genesis", "00" * 32, coinbase, "", [], "00000001",
                  "1d00ffff", "495fab29", True]
        header = build_stratum_header(params, "", "", "495fab29", "7c2bac1d")
        self.assertEqual(header[36:68].hex(),
                         "3ba3edfd7a7b12b27ac72c3e67768f617fc81bc3888a51323a9fb8aa4b1e5e4a")
        self.assertEqual(hash_header(header)[::-1].hex(),
                         "000000000019d6689c085ae165831e934ff763ae46a2a6c172b3f1b60a8ce26f")
        self.assertTrue(validate_stratum_share(params, "", "", "495fab29",
                                              "7c2bac1d", difficulty=1,
                                              extranonce2_size=0))

    def test_version_bits_replace_masked_template_bits(self):
        params = job()
        params[5] = "2000e000"
        rolled = build_stratum_header(params, "aa", "bb", "65000000", "00000000",
                                      "00002000", "0000e000")
        self.assertEqual(rolled[:4], bytes.fromhex("00200020"))
        with self.assertRaisesRegex(ValueError, "exceed"):
            build_stratum_header(params, "aa", "bb", "65000000", "00000000",
                                  "00010000", "0000e000")
        with self.assertRaisesRegex(ValueError, "not negotiated"):
            build_stratum_header(params, "aa", "bb", "65000000", "00000000",
                                  "00002000")
        with self.assertRaisesRegex(ValueError, "missing"):
            build_stratum_header(params, "aa", "bb", "65000000", "00000000",
                                  version_mask="0000e000")

    def test_difficulty_is_exact_finite_and_bounded(self):
        self.assertEqual(target_from_difficulty(1), DIFF_ONE_TARGET)
        self.assertEqual(target_from_difficulty(Decimal("2.5")), DIFF_ONE_TARGET * 2 // 5)
        self.assertEqual(target_from_difficulty(Fraction(1, 3)), DIFF_ONE_TARGET * 3)
        self.assertEqual(target_from_difficulty("0.1"), DIFF_ONE_TARGET * 10)
        self.assertEqual(target_from_difficulty(0.1), DIFF_ONE_TARGET * 10)
        self.assertEqual(target_from_difficulty("1e-100"), MAX_TARGET)
        for invalid in (0, -1, True, "NaN", "Infinity", "1e10000000", "nonsense",
                        Fraction(1 << 5000), Decimal("1e-10000000")):
            with self.subTest(invalid=str(invalid)[:30]), self.assertRaises(ValueError):
                target_from_difficulty(invalid)

    def test_strict_hex_lengths_and_size_binding(self):
        params = job()
        for field in ("  aa", "a", "gg", "aabb\n"):
            with self.subTest(field=field), self.assertRaises(ValueError):
                build_stratum_header(params, field, "bb", "65000000", "00000000")
        for index, value in ((1, "00" * 31), (4, ["aa"]), (5, "2000000"),
                             (6, "1d00ffff00"), (7, "bad"), (8, 1)):
            malformed = job()
            malformed[index] = value
            with self.subTest(index=index), self.assertRaises(ValueError):
                build_stratum_header(malformed, "aa", "bb", "65000000", "00000000")
        with self.assertRaises(ValueError):
            validate_stratum_share(params, "aa", "bb", "65000000", "00000000",
                                    extranonce2_size=4)

    def test_valid_structure_low_difficulty_returns_false(self):
        self.assertFalse(validate_stratum_share(job(), "aa", "bb", "65000000",
                                               "00000000", difficulty=2**200))

    def test_changed_extranonce_changes_the_proof(self):
        params = job()
        first = build_stratum_header(params, "11111111", "00000000", "65000000", "00000000")
        second = build_stratum_header(params, "22222222", "00000000", "65000000", "00000000")
        self.assertNotEqual(hash_header(first), hash_header(second))


if __name__ == "__main__":
    unittest.main()
